def _origin_allowed(websocket: WebSocket) -> bool:
    """Cross-Site WebSocket Hijacking guard. Enforced only when
    VIBONY_ALLOWED_ORIGINS is set (comma-separated) — unset = no check (dev).
    The interviewer WS authenticates by ambient cookie, so an Origin allowlist is
    the real CSWSH defense; the candidate WS uses a token but is checked too."""
    raw = os.getenv("VIBONY_ALLOWED_ORIGINS", "").strip()
    if not raw:
        return True
    allowed = {o.strip() for o in raw.split(",") if o.strip()}
    return websocket.headers.get("origin") in allowed


@router.websocket("/{code}/interviewer")
async def interviewer_ws(
    websocket: WebSocket,
    code: str,
    last_seq: int = Query(default=0, ge=0),  # reject a negative seq
) -> None:
    # CSWSH guard: reject the handshake BEFORE accept → the browser
    # sees an HTTP 403, no app close-code consumed (4403 means cross-tenant).
    if not _origin_allowed(websocket):
        await websocket.close()
        return
    row = await _resolve_session(code)

    if row is None:
        await websocket.accept()
        await websocket.close(code=4404, reason="Session not found")
        return

    claims = read_cookie(websocket)
    if claims is None:
        await websocket.accept()
        await websocket.close(code=4401, reason="Unauthorized")
        return
    user_id, cookie_sv = claims

    sm = get_sessionmaker()
    async with sm() as db:
        user = (
            await db.execute(select(User).where(User.id == user_id))
        ).scalar_one_or_none()
        # Reject a revoked cookie (session_version bumped on logout).
        if user is None or user.session_version != cookie_sv:
            await websocket.accept()
            await websocket.close(code=4401, reason="Unauthorized")
            return

        membership = None
        if row.company_id is not None:
            membership = (
                await db.execute(
                    select(Membership).where(
                        Membership.user_id == user.id,
                        Membership.company_id == row.company_id,
                    )
                )
            ).scalar_one_or_none()
        # company_id is NOT NULL after the migration — None here is a data
        # integrity guard. Either way, the user is not a member → 4403.

        # Extract before the session expires — used for presence registration below.
        interviewer_token = str(user.id)
        interviewer_name = user.email[:64]

    if membership is None:
        await websocket.accept()
        await websocket.close(code=4403, reason="Forbidden")
        return

    if row.status == "completed":
        await websocket.accept()
        await websocket.close(code=4409, reason="Session already ended")
        return

    await websocket.accept()

    # Clean up any stale active state (handles reconnect race), then register.
    presence_registry.disconnect(code, interviewer_token)
    join_result = presence_registry.join(
        code, interviewer_token, interviewer_name, role="interviewer"
    )
    presence_join_ok = isinstance(join_result, PresenceRecord)
    if not presence_join_ok:
        logger.warning("interviewer presence join failed: code=%s reason=%s", code, join_result)

    sub_q: asyncio.Queue[Any] = broker.subscribe(code)
    _interviewer_queues[code].append(sub_q)

    # Broadcast after subscribing so the new interviewer also receives it via sub_q.
    if presence_join_ok:
        _spawn(_broadcast_presence_updated(code))

    current_max_seq = await _get_current_max_seq(row.id)

    await websocket.send_json(
        {
            "kind": "hello",
            "protocol_version": PROTOCOL_VERSION,
            "session_status": row.status,
            "last_seq": current_max_seq,
        }
    )

    await _replay_events(websocket, row.id, code, last_seq, current_max_seq)

    # Send current presence snapshot (includes this interviewer).
    await _ws_send(websocket, {"kind": "presence_updated", "attendees": presence_registry.get_attendees(code)})

    recv_task = asyncio.create_task(_recv_loop_interviewer(websocket, sub_q))

    try:
        await _send_loop(
            websocket,
            sub_q,
            replay_boundary=current_max_seq,
            stop_on_session_end=True,
        )
    except Exception:
        logger.exception("interviewer WS unhandled error: code=%s", code)
    finally:
        try:
            _interviewer_queues[code].remove(sub_q)
        except ValueError:
            pass
        broker.unsubscribe(code, sub_q)
        recv_task.cancel()
        try:
            await recv_task
        except (asyncio.CancelledError, Exception):
            pass
        if presence_join_ok and presence_registry.disconnect(code, interviewer_token):
            _spawn(_broadcast_presence_updated(code))

    try:
        await websocket.close(code=1000, reason="done")
    except Exception:
        pass


# ---------------------------------------------------------------------------
# Recv / Send loops
# ---------------------------------------------------------------------------


async def _recv_loop_interviewer(
    websocket: WebSocket,
    sub_q: asyncio.Queue[Any],
) -> None:
    """Rejects incoming frames; signals send_loop with None on disconnect."""
    while True:
        try:
            await websocket.receive_text()
        except WebSocketDisconnect:
            # offer(): non-blocking — on a bounded queue that already
            # overflowed (and refilled) a blocking put could stall this signal.
            offer(sub_q, None)
            return
        await _ws_send(
            websocket,
            {
                "kind": "error",
                "code": "READ_ONLY",
                "message": "Interviewer endpoint is read-only",
            },
        )


async def _send_loop(
    websocket: WebSocket,
    q: asyncio.Queue[Any],
    replay_boundary: int = 0,
    stop_on_session_end: bool = False,
) -> None:
    """Forwards messages from the Broker queue to the client.

    replay_boundary > 0: events with seq <= boundary are skipped (already re-sent via _replay_events).
    stop_on_session_end=True: finishes after sending session_end or a None sentinel.
    """
    while True:
        msg = await q.get()
        if msg is None:
            return
        # Skip events already re-sent via replay
        if replay_boundary > 0 and msg.get("kind") == "event":
            seq = msg.get("event", {}).get("seq", 0)
            if seq <= replay_boundary:
                continue
        try:
            await websocket.send_json(msg)
        except (WebSocketDisconnect, RuntimeError):
            return
        if (
            stop_on_session_end
            and msg.get("kind") == "event"
            and msg.get("event", {}).get("type") == "session_end"
        ):
            return


async def _ws_send(websocket: WebSocket, msg: dict[str, Any]) -> None:
    """Safe send: swallows disconnect errors."""
    try:
        await websocket.send_json(msg)
    except (WebSocketDisconnect, RuntimeError):
        pass


