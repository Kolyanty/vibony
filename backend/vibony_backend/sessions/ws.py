@dataclass
class PresenceRecord:
    name: str
    token: str
    first_seen: datetime
    last_seen: datetime
    is_active: bool
    role: str = "candidate"


class PresenceRegistry:
    """In-process attendance tracking per session. Lifecycle mirrors AgentHost."""

    def __init__(self) -> None:
        self._records: dict[str, list[PresenceRecord]] = {}
        self._active_tokens: dict[str, set[str]] = {}

    def is_token_active(self, code: str, token: str) -> bool:
        return token in self._active_tokens.get(code, set())

    def join(
        self, code: str, token: str, name: str, *, role: str = "candidate"
    ) -> PresenceRecord | str:
        """Create or update a presence record. Returns the record on success,
        'name_taken', 'invalid_name', or 'duplicate_connection' on failure."""
        name = name.strip()
        if not name or len(name) > 64:
            return "invalid_name"

        records = self._records.setdefault(code, [])
        active_tokens = self._active_tokens.setdefault(code, set())

        # Reject if this token already has an active connection (same candidate, duplicate tab).
        if token in active_tokens:
            return "duplicate_connection"

        name_lower = name.lower()

        # Uniqueness: another *active* record with the same name for a different token
        for r in records:
            if r.is_active and r.token != token and r.name.lower() == name_lower:
                return "name_taken"

        now = datetime.now(UTC)

        # Genuine reconnect: same token AND same name — reuse existing record.
        for r in records:
            if r.token == token and r.name.lower() == name_lower:
                r.last_seen = now
                r.is_active = True
                active_tokens.add(token)
                return r

        # Different name with the same token = new person using the same candidate link.
        # Fall through to create a new record; old one stays as inactive history.
        record = PresenceRecord(
            name=name, token=token, first_seen=now, last_seen=now, is_active=True, role=role
        )
        records.append(record)
        active_tokens.add(token)
        return record

    def disconnect(self, code: str, token: str) -> bool:
        """Mark token as inactive. Returns True if state changed."""
        records = self._records.get(code, [])
        active_tokens = self._active_tokens.get(code, set())
        active_tokens.discard(token)
        now = datetime.now(UTC)
        for r in records:
            if r.token == token and r.is_active:
                r.is_active = False
                r.last_seen = now
                return True
        return False

    def get_attendees(self, code: str) -> list[dict[str, Any]]:
        return [
            {
                "name": r.name,
                "role": r.role,
                "is_active": r.is_active,
                "first_seen": r.first_seen.isoformat(),
                "last_seen": r.last_seen.isoformat(),
            }
            for r in self._records.get(code, [])
        ]

    def get_attendees_masked(self, code: str) -> list[dict[str, Any]]:
        """Same as get_attendees but interviewer names are replaced with
        'Interviewer', 'Interviewer 2', etc. — sent to candidate clients."""
        records = self._records.get(code, [])
        interviewers_by_token: dict[str, int] = {}
        idx = 0
        for r in records:
            if r.role == "interviewer" and r.token not in interviewers_by_token:
                interviewers_by_token[r.token] = idx
                idx += 1

        result = []
        for r in records:
            if r.role == "interviewer":
                n = interviewers_by_token[r.token]
                masked_name = "Interviewer" if n == 0 else f"Interviewer {n + 1}"
            else:
                masked_name = r.name
            result.append({
                "name": masked_name,
                "role": r.role,
                "is_active": r.is_active,
                "first_seen": r.first_seen.isoformat(),
                "last_seen": r.last_seen.isoformat(),
            })
        return result


presence_registry = PresenceRegistry()

# Queues of active interviewer WS subscriptions — used to send interviewer-only frames
# (e.g., presence_alert) without going through the broker.
_interviewer_queues: dict[str, list[asyncio.Queue[Any]]] = defaultdict(list)
# Queues of active candidate-web WS subscriptions — receive masked presence payloads.
_candidate_queues: dict[str, list[asyncio.Queue[Any]]] = defaultdict(list)


async def _broadcast_presence_updated(code: str) -> None:
    """Send role-specific presence_updated: masked names to candidates, full to interviewers."""
    masked_frame = {"kind": "presence_updated", "attendees": presence_registry.get_attendees_masked(code)}
    full_frame = {"kind": "presence_updated", "attendees": presence_registry.get_attendees(code)}
    # offer(): non-blocking with close-on-overflow — a stuck consumer can't
    # stall this broadcast or grow its queue without bound.
    for q in list(_candidate_queues.get(code, [])):
        offer(q, masked_frame)
    for q in list(_interviewer_queues.get(code, [])):
        offer(q, full_frame)


async def _send_presence_alert(code: str, reason: str) -> None:
    frame: dict[str, Any] = {"kind": "presence_alert", "reason": reason}
    for q in list(_interviewer_queues.get(code, [])):
        offer(q, frame)


