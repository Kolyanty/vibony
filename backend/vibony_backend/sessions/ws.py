@router.websocket("/candidate-web")
async def candidate_web_ws(
    websocket: WebSocket,
    token: str = Query(...),
    last_seq: int = Query(default=0, ge=0),  # reject a negative seq
) -> None:
    """WS endpoint for the browser candidate runtime.

    Resolves session by candidate_token (no code in path).
    On first connect creates AgentHost, calls start(), begins fan-out loop.
    On user_message frame: forwards to AgentHost.submit_user_message().
    On inline_bash frame: routes to the inline-bash gate.
    On disconnect: 60 s grace; reconnect within grace cancels termination.
    """
    # CSWSH guard: reject pre-accept (HTTP 403), no app code.
    if not _origin_allowed(websocket):
        await websocket.close()
        return
    sm = get_sessionmaker()
    async with sm() as db:
        from sqlalchemy import select as _select
        # The candidate_token IS the lookup key here (no session code
        # in the path), so this indexed DB equality can't be replaced with a
        # constant-time compare — there is nothing to load the row by first. The
        # token is a 122-bit random uuid4; a timing side-channel on a B-tree unique
        # index lookup is not a realistic recovery vector. Accepted residual.
        row = (
            await db.execute(
                _select(DbSession).where(DbSession.candidate_token == token)
            )
        ).scalar_one_or_none()

    if row is None:
        await websocket.accept()
        await websocket.close(code=4401, reason="Invalid token")
        return

    if row.status == "completed" or is_expired(row.expires_at):
        await websocket.accept()
        await websocket.close(code=4409, reason="Session already ended")
        return

    await websocket.accept()

    # Duplicate connection detection: same token already active → alert interviewers.
    if presence_registry.is_token_active(row.code, token):
        _spawn(_send_presence_alert(row.code, "duplicate_connection"))

    # Cancel any pending grace timer for this session.
    agent_host_registry.cancel_grace(row.code)

    # Subscribe before reading max_seq — race-free replay.
    # NOTE: sub_q is registered in _candidate_queues (the masked-presence fan-out)
    # only AFTER a successful session_join below — a connection that
    # never completes the join handshake must not receive presence_updated frames.
    # The broker subscription itself stays here so session events replay race-free.
    sub_q: asyncio.Queue[Any] = broker.subscribe(row.code)

    # Get or create AgentHost. connect_epoch tags this connection so the
    # disconnect path's connection_closed can't grace-kill a session that has
    # since reconnected.
    host, was_created, connect_epoch = await agent_host_registry.get_or_create(
        row.code,
        row.id,
        row.task_id,
        row.ai_config,
    )

    # Leak-safety: every path after get_or_create — including an
    # exception during hello/replay, before the recv loop — must reach the finally
    # so connection_closed runs, keeping the per-code connection count balanced and
    # still arming a grace timer on a drop mid-handshake. send_task/start_task are
    # created inside the try, so pre-init them for the finally's guarded cleanup.
    send_task: asyncio.Task[None] | None = None
    start_task: asyncio.Task[None] | None = None
    join_succeeded = False
    try:
        current_max_seq = await _get_current_max_seq(row.id)

        await websocket.send_json(
            {
                "kind": "hello",
                "protocol_version": PROTOCOL_VERSION,
                "session_status": row.status,
                "last_seq": current_max_seq,
            }
        )

        await _replay_events(websocket, row.id, row.code, last_seq, current_max_seq)

        send_task = asyncio.create_task(
            _send_loop(
                websocket,
                sub_q,
                replay_boundary=current_max_seq,
                stop_on_session_end=True,
            )
        )

        # Register direct WS callback so bash_confirm_request bypasses broker.
        host.set_ws_send(websocket.send_json)

        # On first connect: kick off AgentHost.start() as a background task so
        # the WS handshake completes before blocking LLM calls.
        if was_created:
            async def start_host() -> None:
                try:
                    await host.start()
                except Exception:
                    # start() already reports AGENT_FAILED; consume the task error.
                    logger.exception("Agent startup failed: code=%s", row.code)

            start_task = asyncio.create_task(start_host())

        # Async mode: anchor the deadline on first connect and (re)start
        # the server-side countdown. The timer is server-authoritative — it
        # survives candidate disconnect, so it is not cancelled in the disconnect
        # path; it is re-established here on reconnect / after a backend restart.
        if row.mode == "async" and row.time_limit_seconds is not None:
            started_at = await mark_async_started(row.id)
            if started_at is not None:
                await async_timer_registry.ensure_running(
                    row.id, row.code, started_at, row.time_limit_seconds
                )

        # Phase 1: wait for session_join (presence gate)
        join_succeeded = await _recv_join_web(websocket, token, row.code)
        # Phase 2: normal session recv loop
        if join_succeeded:
            # Start delivering masked presence frames to this connection
            # only now — after the join handshake. Register before broadcasting so
            # the joining candidate sees itself + current attendees in the frame.
            _candidate_queues[row.code].append(sub_q)
            await _broadcast_presence_updated(row.code)
            # A turn already in flight (reconnect mid-turn) → tell this
            # connection so the "AI is working" indicator shows immediately; the
            # working/idle agent_status frames are advisory and never replayed.
            if host.is_turn_in_flight():
                await _ws_send(websocket, {"kind": "agent_status", "state": "working"})
            await _recv_loop_web(websocket, host, mode=row.mode)
    except WebSocketDisconnect:
        pass
    except Exception:
        logger.exception("candidate-web WS unhandled error: code=%s", row.code)
    finally:
        try:
            _candidate_queues[row.code].remove(sub_q)
        except ValueError:
            pass
        if join_succeeded and presence_registry.disconnect(row.code, token):
            _spawn(_broadcast_presence_updated(row.code))
        host.set_ws_send(None)
        broker.unsubscribe(row.code, sub_q)
        if send_task is not None:
            send_task.cancel()
            try:
                await send_task
            except (asyncio.CancelledError, Exception):
                pass
        if start_task is not None and not start_task.done():
            start_task.cancel()
            try:
                await start_task
            except (asyncio.CancelledError, Exception):
                pass
        # Arm grace termination. connection_closed only fires the timer when the
        # *last* connection for this code closes; running it on
        # every post-get_or_create path keeps the connection count balanced.
        await agent_host_registry.connection_closed(row.code, connect_epoch)


async def _recv_join_web(websocket: WebSocket, token: str, code: str) -> bool:
    """Handle session_join handshake. Returns True on successful join, False on disconnect.

    Sends session_join_ok on success; the caller registers the connection in the
    presence fan-out and broadcasts presence_updated — kept out of here
    so a connection never receives presence frames before its queue is registered.
    """
    while True:
        try:
            data = await websocket.receive_text()
        except WebSocketDisconnect:
            return False

        if len(data) > MAX_FRAME_BYTES:
            await _ws_send(
                websocket,
                {"kind": "error", "code": "FRAME_TOO_LARGE", "message": "Frame exceeds 1 MB"},
            )
            continue

        try:
            frame = json.loads(data)
        except (json.JSONDecodeError, ValueError):
            await _ws_send(
                websocket,
                {"kind": "error", "code": "PAYLOAD_INVALID", "message": "Not valid JSON"},
            )
            continue

        if not isinstance(frame, dict) or frame.get("kind") != "session_join":
            await _ws_send(
                websocket,
                {"kind": "error", "code": "JOIN_REQUIRED", "message": "Send session_join first"},
            )
            continue

        name = frame.get("name")
        if not isinstance(name, str):
            await _ws_send(websocket, {"kind": "session_join_error", "reason": "invalid_name"})
            continue

        result = presence_registry.join(code, token, name)
        if isinstance(result, str):
            await _ws_send(websocket, {"kind": "session_join_error", "reason": result})
            continue

        await _ws_send(websocket, {"kind": "session_join_ok"})
        return True


async def _recv_loop_web(
    websocket: WebSocket, host: AgentHost, mode: str = "live"
) -> None:
    """Receive frames from browser for a web-candidate session."""
    while True:
        try:
            data = await websocket.receive_text()
        except WebSocketDisconnect:
            return

        if len(data) > MAX_FRAME_BYTES:
            await _ws_send(
                websocket,
                {"kind": "error", "code": "FRAME_TOO_LARGE", "message": "Frame exceeds 1 MB"},
            )
            continue

        try:
            frame = json.loads(data)
        except (json.JSONDecodeError, ValueError):
            await _ws_send(
                websocket,
                {"kind": "error", "code": "PAYLOAD_INVALID", "message": "Not valid JSON"},
            )
            continue

        if not isinstance(frame, dict):
            await _ws_send(
                websocket,
                {"kind": "error", "code": "PAYLOAD_INVALID", "message": "Frame must be JSON object"},
            )
            continue

        kind = frame.get("kind")

        if kind == "user_message":
            text = frame.get("text")
            if not isinstance(text, str) or not text.strip():
                await _ws_send(
                    websocket,
                    {"kind": "error", "code": "PAYLOAD_INVALID", "message": "user_message.text must be a non-empty string"},
                )
                continue
            if len(text) > MAX_USER_MESSAGE_CHARS:
                await _ws_send(
                    websocket,
                    {"kind": "error", "code": "PAYLOAD_INVALID", "message": f"user_message.text exceeds {MAX_USER_MESSAGE_CHARS} char limit"},
                )
                continue
            # Single-flight gate spawns + tracks the turn task; a
            # concurrent turn is rejected with BUSY instead of piling up coroutines.
            if not host.start_user_message(text):
                await _ws_send(
                    websocket,
                    {"kind": "error", "code": "BUSY", "message": "A turn is already in progress"},
                )
            continue

        if kind == "inline_bash":
            cmd = frame.get("cmd")
            if not isinstance(cmd, str) or not cmd.strip():
                await _ws_send(
                    websocket,
                    {"kind": "error", "code": "PAYLOAD_INVALID", "message": "inline_bash.cmd must be a non-empty string"},
                )
                continue
            if len(cmd) > 4096:
                await _ws_send(
                    websocket,
                    {"kind": "error", "code": "PAYLOAD_INVALID", "message": "inline_bash.cmd exceeds 4096 char limit"},
                )
                continue
            # Serialise candidate inline-bash per session — a second
            # concurrent command is rejected with BUSY, not run alongside the first.
            if not host.start_inline_bash(cmd):
                await _ws_send(
                    websocket,
                    {"kind": "error", "code": "BUSY", "message": "A command is already running"},
                )
            continue

        if kind == "bash_confirm_response":
            cmd_id = frame.get("cmd_id")
            choice = frame.get("choice")
            _VALID_CHOICES = {"allow_once", "allow_prefix", "deny"}
            if isinstance(cmd_id, str) and choice in _VALID_CHOICES:
                host.resolve_bash_confirm(cmd_id, choice)
            continue

        if kind == "session_submit":
            # Candidate ends an async session early. Terminal signal is a
            # session_end event with reason='submitted' (+ assessment_pending
            # stub); send_loop delivers it and the candidate UI shows the
            # end-screen. The loop stays alive — same as the interviewer-end and
            # timeout paths, which never force-close the web candidate WS.
            if mode != "async":
                await _ws_send(
                    websocket,
                    {
                        "kind": "error",
                        "code": "NOT_ASYNC",
                        "message": "session_submit is only valid for async sessions",
                    },
                )
                continue
            await end_async_session(host._session_id, host._session_code, "submitted")
            async_timer_registry.cancel(host._session_code)
            continue

        if kind == "fs_request":
            # Browser sends fs_request; backend routes to WebFsProxy → sandbox.
            req_id = frame.get("id")
            op = frame.get("op")
            path = frame.get("path")
            content = frame.get("content")
            if not req_id or not op:
                await _ws_send(
                    websocket,
                    {"kind": "error", "code": "PAYLOAD_INVALID", "message": "fs_request missing id or op"},
                )
                continue
            web_proxy = web_fs_proxy_registry.get(host._session_code)
            if web_proxy is None:
                await _ws_send(websocket, {"kind": "fs_response", "id": req_id, "error": "sandbox not ready"})
                continue
            if op == "write":
                async def reply(result: dict[str, Any], request_id: str = req_id) -> None:
                    await _ws_send(websocket, {"kind": "fs_response", "id": request_id, **result})

                if not host.start_candidate_file_write(web_proxy, path, content, reply):
                    await reply({"error": "Save queue is full or session is closing. Retry the save."})
                continue
            else:
                result = await web_proxy.request(op, path=path, content=content)
            await _ws_send(websocket, {"kind": "fs_response", "id": req_id, **result})
            continue

        await _ws_send(
            websocket,
            {"kind": "error", "code": "PAYLOAD_INVALID", "message": f"Unexpected frame kind: {kind!r}"},
        )
