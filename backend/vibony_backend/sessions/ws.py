async def _resolve_session(code: str) -> DbSession | None:
    sm = get_sessionmaker()
    async with sm() as db:
        return (
            await db.execute(select(DbSession).where(DbSession.code == code))
        ).scalar_one_or_none()


async def _get_current_max_seq(session_id: uuid.UUID) -> int:
    sm = get_sessionmaker()
    async with sm() as db:
        return (
            await db.execute(
                select(func.coalesce(func.max(Event.seq), 0)).where(
                    Event.session_id == session_id
                )
            )
        ).scalar() or 0


async def _replay_events(
    websocket: WebSocket,
    session_id: uuid.UUID,
    code: str,
    from_seq: int,
    to_seq: int,
) -> None:
    """Re-send events (from_seq, to_seq] directly to the WebSocket."""
    if from_seq >= to_seq:
        return
    sm = get_sessionmaker()
    async with sm() as db:
        events = (
            await db.execute(
                select(Event)
                .where(
                    Event.session_id == session_id,
                    Event.seq > from_seq,
                    Event.seq <= to_seq,
                )
                .order_by(Event.seq)
            )
        ).scalars().all()

    for ev in events:
        await _ws_send(
            websocket,
            {
                "kind": "event",
                "event": {
                    "id": str(ev.id),
                    "seq": ev.seq,
                    "session_code": code,
                    "timestamp": ev.client_timestamp.isoformat(),
                    "type": ev.type,
                    "payload": ev.payload,
                },
            },
        )


