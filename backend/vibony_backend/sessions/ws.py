# Retain fire-and-forget tasks (presence broadcasts, async
# file_changed emits). asyncio only holds a weak reference to a bare
# create_task() result, so without this an unawaited task can be garbage-
# collected mid-flight → a presence update silently never runs (stale attendee
# list). The done-callback discards the entry so the set doesn't grow.
_background_tasks: set[asyncio.Task[Any]] = set()


def _spawn(coro: Any) -> asyncio.Task[Any]:
    """Schedule a fire-and-forget coroutine, retained until it completes."""
    task = asyncio.create_task(coro)
    _background_tasks.add(task)
    task.add_done_callback(_background_tasks.discard)
    return task


MAX_FRAME_BYTES = 1_000_000  # 1 MB
# Max chars in a candidate user_message.text. The 1 MB frame cap is
# the outer bound; this is the per-message LLM-context cap, symmetric with the
# 4096-char inline_bash.cmd cap. Pasting large blobs belongs in files, not chat.
MAX_USER_MESSAGE_CHARS = 16_000


