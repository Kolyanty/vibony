"""WebSocket endpoints for sessions.

Candidate endpoint (browser, web runtime): wss://.../sessions/candidate-web?token=<candidate_token>&last_seq=<int>
  - Handshake: backend sends `hello` (protocol_version, session_status, last_seq).
  - Replay: if the client passed last_seq < the current max, the backend re-sends the missed events.
  - Bidirectional: the browser sends user_message/inline_bash/fs_request/session_submit;
    events are generated by the backend (AgentHost), not the client. The backend assigns seq,
    writes to the DB via store_event, and fans out to subscribers via the Broker.
  - After `session_end`: the broker message reaches the client, then the WS
    closes gracefully (1000).

Interviewer endpoint: wss://.../sessions/{code}/interviewer?last_seq=<int>
  - Authentication: user_session cookie. Membership is checked against
    session.company_id. 4401 — missing/invalid cookie; 4403 — cross-tenant.
  - Read-only: receives broadcast + replay, incoming frames → `error`.
  - Closes gracefully after session_end.

Close codes (from ws-contract.md):
  4401 — no/invalid cookie (interviewer) or invalid candidate_token (candidate)
  4403 — cross-tenant (interviewer: user not a member of session's company)
  4404 — session not found
  4409 — session already ended (when opening a WS to a completed session)

Frame limit: 1 MB.

Interviewer concurrency:
  _recv_loop_interviewer — rejects incoming frames; signals send_loop on disconnect.
  _send_loop (stop_on_session_end=True) — forwards broadcasts, stops after session_end.

Replay pattern (race-free):
  1. subscribe(broker) — start buffering live events.
  2. Read current_max_seq from the DB.
  3. Send hello with last_seq=current_max_seq.
  4. Re-send the missed events: seq ∈ (client_last_seq, current_max_seq].
  5. Start send_loop with replay_boundary=current_max_seq — it skips
     events with seq <= boundary (already sent in step 4).
"""

